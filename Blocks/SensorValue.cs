using System;

namespace BitFab.KW1281Test.Blocks
{
    public class SensorValue
    {
        public byte SensorID { get; }

        public byte A { get; }

        public byte B { get; }

        public SensorValue(byte sensorID, byte a, byte b)
        {
            SensorID = sensorID;
            A = a;
            B = b;
        }

        /// <summary>A:B as a signed 16-bit value, A is the high byte.</summary>
        private int S16 => unchecked((short)((A << 8) | B));

        private int U16 => (A << 8) | B;

        public override string ToString()
        {
            // https://www.blafusel.de/obd/obd2_kw1281.html#7
            return SensorID switch
            {
                1 => $"{0.2 * A * B} rpm",
                2 => $"{(A * 0.002 * B):F1} %",
                3 => $"{(0.002 * A * B):F1} Deg",
                4 => $"{(Math.Abs(B - 127) * 0.01 * A):F1} \u00B0{(B > 127 ? "ATDC" : "BTDC")}", // Degrees
                5 => $"{(A * (B-100) * 0.1):F1} \u00B0C", // Degrees C
                6 => $"{(0.001 * A * B):F1} V",
                7 => $"{0.01 * A * B} km/h",
                8 => $"{(0.1 * A * B):F1}",
                9 => $"{((B - 127) * 0.02 * A):F1} Deg",
                10 => $"{(B == 0 ? "Cold" : "Warm")}",
                11 => $"{(0.0001 * A * (B - 128) + 1):F1}",
                12 => $"{(0.001 * A * B):F1} \u2126", // Ohm
                13 => $"{((B - 127) * 0.001 * A):F1} mm",
                14 => $"{(0.005 * A * B):F1} bar",
                15 => $"{(0.01 * A * B):F1} ms",
                16 => $"{Convert.ToString(A, 2).PadLeft(8, '0')} {Convert.ToString(B, 2).PadLeft(8, '0')}",
                17 => $"\"{(char)A}{(char)B}\"",
                18 => $"{(0.04 * A * B):F1} mbar",
                19 => $"{(A * B * 0.01):F1} l",
                20 => $"{(A * (B - 128) / 128.0):F1} %",
                21 => $"{(0.001 * A * B):F1} V",
                22 => $"{(0.001 * A * B):F1} ms",
                23 => $"{(B / 256.0 * A):F1} %",
                24 => $"{(0.001 * A * B):F1} A",
                25 => $"{((B * 1.421) + (A / 182.0)):F1} g/s",
                26 => $"{B - A} C",
                27 => $"{(Math.Abs(B - 128) * 0.01 * A):F1} \u00B0{(B < 128 ? "ATDC" : "BTDC")}", // Degrees
                28 => $"{B - A}",
                29 => $"{(B<A ? "Map 1" : "Map 2")}",
                30 => $"{(B / 12.0 * A):F1} Deg k/w",
                31 => $"{(B / 2560.0 * A):F1}",
                32 => $"{(B>128 ? B-256 : B)}",
                33 => $"{(A == 0 ? 100.0*B : 100.0*B/A):F1} %",
                34 => $"{((B - 128) * 0.01 * A):F1} Deg k/w", // crank angle ("KW" = Kurbelwelle), not kW
                35 => $"{(0.01 * A * B):F1} l/h",
                36 => $"{A * 2560 + B * 10} km",
                // 37 => ???,
                38 => $"{((B - 128) * 0.001 * A):F1} Deg k/w",
                39 => $"{(B/256.0*A):F1} mg/h",
                40 => $"{(B * 0.1 + (25.5 * A) - 400):F1} A",
                41 => $"{(B + A * 255)} Ah",
                42 => $"{(B * 0.1 + (25.5 * A) - 400):F1} Kw",
                43 => $"{(B * 0.1 + (25.5 * A)):F1} V",
                44 => $"{A:D2}:{B:D2}",
                45 => $"{(0.1 * A * B / 100.0):F1}",
                46 => $"{((A * 256 + B - 32768) * 0.00275):F1} Deg k/w",
                47 => $"{((B - 128) * A)} ms",
                48 => $"{B + A * 255}",
                49 => $"{(B / 4.0 * A * 0.1):F1} mg/h",
                50 => $"{(A == 0 ? (B - 128) / 0.01 : (B - 128) / (0.01 * A)):F1} mbar",
                51 => $"{(((B - 128) / 255.0) * A):F1} mg/h",
                52 => $"{(B * 0.02 * A - A):F1} Nm",
                53 => $"{((B - 128) * 1.4222 + 0.006 * A):F1} g/s",
                54 => $"{A * 256 + B}",
                55 => $"{(A * B / 200.0):F1} s",
                56 => $"{A * 256 + B} WSC",
                57 => $"{A * 256 + B + 65536} WSC",
                58 => $"{unchecked((sbyte)B) * 1.023:F1} /s",
                59 => $"{((A * 256 + B) / 32768.0):F1}",
                60 => $"{((A * 256 + B) * 0.01):F1} sec",
                61 => $"{(A==0 ? (B - 128) : (B - 128) / A):F1}",
                62 => $"{(0.256 * A * B):F1} S",
                63 => $"\"{(char)A}{(char)B}\"?",
                64 => $"{A+B} \u2126", // Ohm
                65 => $"{(0.01 * A * (B - 127)):F1} mm",
                66 => $"{((A * B) / 511.12):F1} V",
                67 => $"{S16 * 2.5:F1} Deg",
                68 => $"{S16 * 0.1358:F1} deg/s",
                69 => $"{S16 * 0.3255:F1} bar",
                70 => $"{S16 * 0.192:F1} m/s\u00B2", // squared
                // 71-181: cross-checked against the table in domnulvlad/KLineKWP1281Lib (own code).
                // S16/U16 = A:B as a signed/unsigned 16-bit value, A is the high byte.
                71 => $"{A * B} cm",
                72 => $"{(A * 255 + B * (211 - A)) / 4080.0:F2} V",
                73 => $"{A * B * 0.01:F2} Ohm",
                74 => $"{0.1 * A * B:F1} months",
                75 => $"{A * 256 + B}",
                76 => $"{A * 255 + B} kOhm",
                77 => $"{(255 * A + B * 60) / 4080.0:F2} V",
                78 => $"{unchecked((sbyte)B) * 1.819:F1} /s",
                79 => $"{B}",
                80 => $"{U16 / 100.0:F2} kOhm",
                81 => $"{S16 * 0.04375:F1} Deg",
                82 => $"{S16 * 0.00981:F2} m/s²",
                83 => $"{S16 * 0.01:F2} bar",
                84 => $"{S16 * 0.0973:F2} m/s²",
                85 => $"{S16 * 0.002865:F2} deg/s",
                86 => $"{A * B * 0.1:F1} A",
                87 => $"{A * (B - 128) * 0.1:F1} deg/s",
                88 => $"{A * B * 0.01:F2} kOhm",
                89 => $"{A * 256 + B} h",
                90 => $"{A * B * 0.1:F1} kg",
                91 => $"{A * (B - 128) * 0.1:F1} Deg",
                92 => $"{A * B} km",
                93 => $"{(B - 128) * A * 0.001:F2} Nm",
                94 => $"{A * (B - 128) * 0.1:F1} Nm",
                96 => $"{A * B * 0.1:F1} mbar",
                97 => $"{(B - A) * 5} °C",
                98 => $"{A * B * 0.1:F1} /km",
                99 => $"{S16}",
                100 => $"{A * B * 0.1:F1} bar",
                101 => $"{A * B * 0.001:F3} l/mm",
                102 => $"{A * B * 0.1:F1} mm",
                103 => $"{A + B * 0.05:F2} V",
                104 => $"{(B - 128) * A * 0.2:F1} ml",
                105 => $"{(B - 128) * A * 0.01:F2} m",
                106 => $"{(B - 128) * A * 0.1:F1} km/h",
                112 => $"{(B - 128) * A * 0.001:F3} Deg",
                113 => $"{(B - 128) * A * 0.01:F2}",
                114 => $"{(B - 128) * A} m",
                115 => $"{S16} W",
                116 => $"{S16} rpm",
                117 => $"{(B - 64) * A * 0.01:F1} °C",
                119 => $"{A * B * 0.01:F1} %",
                120 => $"{A * B * 1.41:F1} Deg",
                121 => $"{(B * 256 + A) * 0.5:F1}",
                122 => $"{(B * 256 + A - 32768) * 0.01:F2}",
                124 => $"{A * B * 0.1:F1} mA",
                125 => $"{A - B} dB",
                126 => $"{A * B * 0.1:F1}",
                127 => $"{2000 + (B & 0x7F):D4}.{((A & 7) << 1) | (B >> 7):D2}.{A >> 3:D2}",
                128 => $"{A * B} rpm",
                129 => $"{A * B / 256.0:F1} %",
                130 => $"{A * B / 2560.0:F2} A",
                131 => $"{A * B * 0.5 - 30:F1} Deg",
                132 => $"{A * B * 0.5:F1} Deg",
                133 => $"{A * B / 256.0:F2} V",
                134 => $"{A * B} km/h",
                135 => $"{A * B}",
                137 => $"{A * B * 0.01:F2} ms",
                138 => $"{A * B * 0.001:F2} V",
                143 => $"{(B - 128) * A * 0.01:F1} Deg k/w",
                144 => $"{A * B * 0.01:F2} l/h",
                145 => $"{A * B * 0.01:F2}",
                146 => $"{1 + (B - 128) * A * 0.0001:F3}",
                148 => $"{(B - 128) * A * 0.25:F1}",
                149 => $"{(B - 100) * A * 0.1:F1} °C",
                150 => $"{(256 * B + A) / 180.0:F1} g/s",
                151 => $"{(B - 128) * A * 0.01:F1} Deg k/w",
                152 => $"{A * B * 0.025:F1} mg/h",
                153 => $"{(B - 128) * A / 255.0:F1} mg/h",
                154 => $"{A * B} Deg",
                155 => $"{A * B * 0.01 - 90:F1} Deg",
                156 => $"{U16} cm",
                157 => $"{S16} cm",
                158 => $"{U16 * 0.01:F1} km/h",
                159 => $"{((B - 127) * 256 + A) * 0.1:F1} °C",
                162 => $"{A * B * 0.448:F1} Deg",
                164 => $"{(B > 100 && B <= 200 ? B - 100 : B)} %",
                165 => $"{B * 256 + A - 32768} mA",
                166 => $"{S16 * 2.5:F1} deg/s",
                167 => $"{A * B * 0.001:F3} mOhm",
                168 => $"{U16 * 0.01:F2} %",
                169 => $"{A * B + 200} mV",
                170 or 171 => $"{A * B / 2560.0:F2} g",
                172 => $"{A * B} mg/km",
                173 => $"{A * B * 0.1:F1} mg/s",
                174 => $"{A * B * 0.01:F2} km",
                175 => $"{A * B * 0.005:F2} bar",
                176 => $"{A * B * 0.1:F1} ppm",
                177 => $"{(A - 128) * 256 + B} Nm",
                178 => $"{((A - 128) * 256 + B) * 6.0 / 51:F1} deg/s",
                179 => $"{U16 * 10}",
                180 => $"{A * B / 256.0:F1} kg/h",
                181 => $"{A * B * 0.001:F3} mg/s",
                107 => $"{A:X2} {B:X2}",
                142 => $"\"{(char)A}{(char)B}\"",
                161 => $"{Convert.ToString(A, 2).PadLeft(8, '0')} {Convert.ToString(B, 2).PadLeft(8, '0')}",
                163 => $"{A:D2}:{B:D2}",
                _ => $"({SensorID} {A} {B})",
            };
        }
    }
}
